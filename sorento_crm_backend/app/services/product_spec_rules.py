# canonical form and validation (contract sections 1.1 and 3)
# --------------------------------------------------------------------------- #
def _upper_list(raw) -> list[str]:
    """Upper case, trimmed, no empties, no duplicates, order kept."""
    out: list[str] = []
    if isinstance(raw, str):
        raw = [raw]
    for item in raw or []:
        word = " ".join(str(item or "").upper().split())
        if word and word not in out:
            out.append(word)
    return out


def _clean_number(raw):
    if raw is None or raw == "":
        return None
    value = float(raw)
    return int(value) if value.is_integer() else value


def _clean_pick(raw):
    if isinstance(raw, bool):
        return None
    if isinstance(raw, str):
        text = raw.strip().upper()
        if text in {"L", "W", "H"}:
            return text
        if text.isdigit():
            raw = int(text)
        else:
            return None
    if isinstance(raw, float) and raw.is_integer():
        raw = int(raw)
    return raw if raw in (1, 2, 3, 4) else None


def clean_builder(builder: dict) -> dict:
    """A builder in its stored form. Assumes `validate_rules` has accepted it.

    Only the fields the kind uses, words upper case, empty optional parts dropped, so
    two builders that mean the same thing are the same JSON (the seed repair and the
    fold both compare builders by that JSON).
    """
    kind = builder.get("kind")
    out: dict[str, Any] = {"kind": kind}
    if kind in {"words", "number", "size"} and builder.get("look_in"):
        out["look_in"] = builder["look_in"]
    if kind == "words":
        out["words"] = _upper_list(builder.get("words"))
        if builder.get("at_end"):
            out["at_end"] = True
        skip = _upper_list(builder.get("skip_after"))
        if skip:
            out["skip_after"] = skip
        out["value"] = builder.get("value")
    elif kind == "number":
        for part in ("before", "after"):
            words = _upper_list(builder.get(part))
            if words:
                out[part] = words
        if builder.get("written_in"):
            out["written_in"] = builder["written_in"]
        floor = _clean_number(builder.get("ignore_below"))
        if floor is not None:
            out["ignore_below"] = floor
        skip = _upper_list(builder.get("skip_after"))
        if skip:
            out["skip_after"] = skip
    elif kind == "size":
        out["pick"] = _clean_pick(builder.get("pick"))
    elif kind == "code":
        out["code_match"] = builder.get("code_match")
        out["texts"] = _upper_list(builder.get("texts"))
        out["value"] = builder.get("value")
    elif kind == "product":
        out["fact"] = builder.get("fact")
    only_when = builder.get("only_when")
    if isinstance(only_when, dict) and only_when.get("spec"):
        out["only_when"] = {
            "spec": str(only_when["spec"]).strip(),
            "is": bool(only_when.get("is", True)),
            "values": [str(v).strip() for v in only_when.get("values") or [] if str(v).strip()],
        }
    return out


def builder_identity(builder: dict) -> str:
    """One string per meaning, for comparing a stored rule with a shipped one."""
    return json.dumps(builder or {}, sort_keys=True, default=str)


def _refuse(message: str, *, status_code: int = 400, code: str = "spec_registry_bad_rule"):
    from app.services.error_handler import AppException

    return AppException(status_code=status_code, message=message, code=code)


def _value_for(raw, *, data_type: str, allowed: list[str], n: int):
    """The value a Words or Code rule sets, in the shape the spec stores, or refused."""
    data_type = (data_type or "").lower()
    if raw is None or (isinstance(raw, str) and not raw.strip()):
        raise _refuse(f"Rule {n}: pick the value it sets.")
    if data_type == "boolean":
        if raw is True or str(raw).strip().lower() in {"true", "yes", "1"}:
            return True
        raise _refuse(f"Rule {n}: pick the value it sets.")
    if data_type == "numeric":
        try:
            return _clean_number(raw)
        except (TypeError, ValueError):
            raise _refuse(f"Rule {n}: pick the value it sets.")
    value = raw if not isinstance(raw, str) else raw.strip()
    if allowed and str(value) not in allowed:
        # Named without the choice's code name (D15): the person is looking at labels.
        raise _refuse(
            f"Rule {n} sets a value this specification does not have. Pick one of its "
            "choices, or add the choice first.",
            code="spec_registry_unknown_rule_value",
        )
    return value


def validate_rules(
    rules,
    *,
    spec_key: str | None = None,
    data_type: str = "",
    allowed_values: list | None = None,
) -> list[dict]:
    """Every rule checked and put in its stored form, `[{"builder": cleaned}, ...]`.

    Refused with a 400 naming the missing part in plain words, never a code name
    (contract section 3, D15). A rule sent with the `pattern` the screen compiled is held
    to the server's compile of the same builder, and a mismatch is a 422: the two
    compilers disagree, and saving would run something the screen did not show.
    """
    if (spec_key or "").strip().lower() == BRAND_KEY:
        raise _refuse(BRAND_IS_NOT_A_SPEC, code="spec_registry_brand")
    allowed = [str(v) for v in (allowed_values or [])]
    closed = allowed if (data_type or "").lower() == "enum" else []

    cleaned_rules: list[dict] = []
    for n, rule in enumerate(rules or [], start=1):
        builder = builder_of(rule)
        if not builder:
            raise _refuse(f"Rule {n} has no parts. Open it and pick what it reads.")
        kind = builder.get("kind")
        if kind not in KINDS:
            raise _refuse(f"Rule {n}: pick a kind (Words, Number, Size, Code or Product).")

        if kind in {"words", "number", "size"}:
            look_in = builder.get("look_in")
            if look_in is not None and look_in not in LOOK_INS:
                raise _refuse(f"Rule {n}: pick where to look.")

        if kind == "words":
            if not _upper_list(builder.get("words")):
                raise _refuse(f"Rule {n}: add at least one word to find.")
            value = _value_for(builder.get("value"), data_type=data_type, allowed=closed, n=n)
        elif kind == "number":
            if not (_upper_list(builder.get("before")) or _upper_list(builder.get("after"))):
                raise _refuse(f"Rule {n}: add at least one word next to the number.")
            written_in = builder.get("written_in")
            if written_in is not None and written_in not in WRITTEN_IN_SCALE:
                raise _refuse(f"Rule {n}: pick the unit the number is written in.")
            try:
                _clean_number(builder.get("ignore_below"))
            except (TypeError, ValueError):
                raise _refuse(f"Rule {n}: the number to ignore below must be a number.")
        elif kind == "size":
            if _clean_pick(builder.get("pick")) is None:
                raise _refuse(f"Rule {n}: pick which number of the size to read.")
        elif kind == "code":
            if builder.get("code_match") not in CODE_MATCHES:
                raise _refuse(f"Rule {n}: pick how the code is matched.")
            if not _upper_list(builder.get("texts")):
                raise _refuse(f"Rule {n}: add at least one piece of code to find.")
            value = _value_for(builder.get("value"), data_type=data_type, allowed=closed, n=n)
        elif kind == "product":
            if builder.get("fact") not in FACTS:
                raise _refuse(f"Rule {n}: pick which fact about the product to read.")

        only_when = builder.get("only_when")
        if only_when is not None:
            spec = (
                str((only_when or {}).get("spec") or "").strip()
                if isinstance(only_when, dict)
                else ""
            )
            values = (
                [v for v in only_when.get("values") or [] if str(v).strip()]
                if isinstance(only_when, dict)
                else []
            )
            if not spec or not values or spec.lower() == BRAND_KEY:
                raise _refuse(
                    f"Rule {n}: pick the specification and at least one value for Only when."
                )

        sent_pattern = rule.get("pattern") if isinstance(rule, dict) else None
        if sent_pattern is not None and sent_pattern != compile_builder(builder)["pattern"]:
            raise _refuse(
                f"Rule {n} does not match what the screen showed. Open it and save it again.",
                status_code=422,
                code="spec_rule_builder_mismatch",
            )

        cleaned = clean_builder(builder)
        if kind in {"words", "code"}:
            cleaned["value"] = value
        cleaned_rules.append({"builder": cleaned})
    return cleaned_rules


# --------------------------------------------------------------------------- #
# folding neighbours
# --------------------------------------------------------------------------- #
def _fold_key(builder: dict) -> str | None:
    """What two Words rules must share to fold into one: everything but the words."""
    if builder.get("kind") != "words":
        return None
    return builder_identity({k: v for k, v in builder.items() if k != "words"})


def fold_rules(rules: list[dict]) -> list[dict]:
    """Neighbouring Words rules with the same answer become one rule with several words.

    Order is kept: the folded rule sits where the first of its neighbours sat, and its
    words keep their order, so the first match still wins exactly as it did. Only
    NEIGHBOURS fold - two rules with the same answer and a different rule between them
    stay apart, or the one between would change which rule fires first. Code rules do
    not fold: each reads one convention and the list reads them one per row.
    """
    folded: list[dict] = []
    for rule in rules or []:
        builder = builder_of(rule)
        key = _fold_key(builder)
        if folded and key is not None and key == _fold_key(builder_of(folded[-1])):
            previous = dict(folded[-1])
            merged = dict(builder_of(previous))
            merged["words"] = _upper_list(
                list(merged.get("words") or []) + list(builder.get("words") or [])
            )
            previous["builder"] = merged
            folded[-1] = previous
            continue
        folded.append(dict(rule))
    return folded


