"""The rule engine: a rule is a set of picks, compiled here, and nobody types a pattern.

Plan: `PLAN-product-specs-non-technical-26sep.md` D5 (owner ruling, 26 Sep 2026, Q5 and
Q6: "if the rule engine is not simple enough to cover, then the engine is the problem").
Contract: `CONTRACT-product-specs-rule-engine.md`, sections 1 to 3. A stored rule is
`{"builder": {...}}` and nothing else (shipped rules also carry `"_seed": true`); the
matching fields are compiled from the builder at run time, so no stored rule holds a
regular expression and no screen can show one.

Five kinds, one matching rulebook for all of them (contract section 2):

  * words   - words in the text; sets the choice the person picked
  * number  - a number next to words (before, after, or between them)
  * size    - one number out of a size such as 1500 x 750 x 630, or the labelled one
  * code    - the product code contains / starts with / ends with some text
  * product - a fact already on the product: its category's class, what its name says
              it is, its length / width / height

`compile_builder` is mirrored line for line by `lib/ruleSentence.ts::compileBuilder` in
the frontend, escaping included, and both are pinned by one shared fixture
(`lib/__fixtures__/rule-builders.json`, regenerated by
`scripts/generate_rule_builder_fixture.py`). A save whose screen-compiled pattern
disagrees with this one is refused, so the pattern the engine runs is never something
the screen did not show.

This module is a leaf: it imports nothing from the other spec services, so derivation,
the registry and the API can all import it.
"""

from __future__ import annotations

import json
import re
from functools import lru_cache
from typing import Any

KINDS = ("words", "number", "size", "code", "product")
LOOK_INS = ("any", "description", "flyer", "name")
CODE_MATCHES = ("contains", "starts_with", "ends_with")
FACTS = ("class", "name", "length", "width", "height")
SIZE_PICKS = (1, 2, 3, 4, "L", "W", "H")
# What a number written in another unit is multiplied by: the catalogue stores mm.
WRITTEN_IN_SCALE = {"centimetres": 10, "metres": 1000}

# The one key that is never a specification (#1286, D1).
BRAND_KEY = "brand"
BRAND_IS_NOT_A_SPEC = "Brand is not a specification. The product's brand is on its Details tab."

# Which text a rule reads when its builder does not say. Product class reads the product
# name without sizes and extras; everything else reads the description or the flyer.
DEFAULT_LOOK_IN_BY_KEY = {"class": "name"}


def default_look_in(spec_key: str | None) -> str:
    return DEFAULT_LOOK_IN_BY_KEY.get(spec_key or "", "any")


# --------------------------------------------------------------------------- #
# the compiler (contract section 2 and 2.1)
# --------------------------------------------------------------------------- #
# JavaScript's escape set, not `re.escape`: Python's also escapes `-`, `&`, `#` and
# whitespace, which would compile a pattern the browser never produces and refuse the
# save as a mismatch.
_JS_REGEX_SPECIALS = re.compile(r"[.*+?^${}()|[\]\\]")


def _escape(raw: str) -> str:
    return _JS_REGEX_SPECIALS.sub(lambda match: "\\" + match.group(0), raw or "")


def _phrase(phrase: str) -> str:
    """One phrase: "..." splits it into segments that may sit apart in one sentence,
    and inside a segment a space, a hyphen or nothing all count between the words.
    Each segment is bounded by letters only, so "LED" never matches inside "SEALED"."""
    segments = [part.strip() for part in str(phrase or "").upper().split("...")]
    compiled = []
    for segment in (part for part in segments if part):
        tokens = [_escape(token) for token in re.split(r"[\s-]+", segment) if token]
        compiled.append("(?<![A-Z])" + _GAP.join(tokens) + "(?![A-Z])")
    return "[^.]*?".join(compiled)


# A space, a hyphen or nothing, between the words of a phrase.
_GAP = r"[\s\-]*"


def _alternation(phrases: list[str]) -> str:
    return f"(?:{'|'.join(_phrase(p) for p in phrases)})"


_NUMBER = r"(\d+(?:\.\d+)?)"
# A number read BEFORE a word must stand on its own: a letter or digit touching it,
# directly or across a hyphen, means it is part of a code (the 1008 in SRTKS1008L).
_NUMBER_GUARD = r"(?<![A-Z0-9.])(?<![A-Z0-9]-)"

_SIZE_PART = r"(?:([LWHD])\s*)?(\d+(?:\.\d+)?)\s*(?:MM)?"
SIZE_PATTERN = (
    rf"{_SIZE_PART}\s*[X*]\s*{_SIZE_PART}"
    rf"(?:\s*[X*]\s*{_SIZE_PART})?"
    rf"(?:\s*[X*]\s*{_SIZE_PART})?"
)


def _words_pattern(words: list[str], at_end: bool) -> str:
    return _alternation(words) + (r"\s*$" if at_end else "")


def _number_pattern(before: list[str], after: list[str]) -> str:
    near = _alternation(before) if before else ""
    far = _alternation(after) if after else ""
    if after and before:
        return rf"{far}[\s\-:,]*{_NUMBER}[\s\-]*{near}(?![A-Z])"
    if after:
        return rf"{far}[\s\-:,]*{_NUMBER}"
    return rf"{_NUMBER_GUARD}{_NUMBER}[\s\-]*{near}(?![A-Z])"


def _skip_pattern(skip_after) -> str | None:
    if not skip_after:
        return None
    return rf"(?<![A-Z]){_alternation(list(skip_after))}[\s\-:,(]*$"


def compile_builder(builder: dict) -> dict:
    """The engine fields one builder compiles to (contract 2.1). Never raises.

    Mirrors `compileBuilder` in `lib/ruleSentence.ts` exactly, including for a builder
    that would not pass validation, so the two can be compared on any input.
    """
    builder = builder if isinstance(builder, dict) else {}
    kind = builder.get("kind")
    out: dict[str, Any] = {
        "kind": kind,
        "scope": None,
        "pattern": None,
        "capture": None,
        "skip": None,
        "scale": None,
        "min": None,
        "pick": None,
        "code_match": None,
        "texts": None,
        "fact": None,
    }
    if kind == "words":
        out.update(
            scope=builder.get("look_in"),
            pattern=_words_pattern(list(builder.get("words") or []), bool(builder.get("at_end"))),
            skip=_skip_pattern(builder.get("skip_after")),
        )
    elif kind == "number":
        written_in = builder.get("written_in")
        out.update(
            scope=builder.get("look_in"),
            pattern=_number_pattern(
                list(builder.get("before") or []), list(builder.get("after") or [])
            ),
            capture=1,
            skip=_skip_pattern(builder.get("skip_after")),
            scale=WRITTEN_IN_SCALE.get(written_in) if written_in else None,
            min=builder.get("ignore_below"),
        )
    elif kind == "size":
        out.update(scope=builder.get("look_in"), pattern=SIZE_PATTERN, pick=builder.get("pick"))
    elif kind == "code":
        out.update(
            scope="code",
            code_match=builder.get("code_match"),
            texts=[str(text).upper() for text in (builder.get("texts") or [])],
        )
    elif kind == "product":
        out.update(scope="product", fact=builder.get("fact"))
    return out


@lru_cache(maxsize=4096)
def _regex(pattern: str) -> re.Pattern:
    return re.compile(pattern)


# Compiled once per builder object, not once per product: a catalogue run reads every
# rule for each of 11,000 codes with the same loaded rule dicts. Keyed on the object's
# identity and holding the object itself, so a freed dict can never hand its id to a
# different builder and inherit its compile.
_COMPILED: dict[int, tuple[dict, dict]] = {}
_COMPILED_LIMIT = 20000


def compiled_for(builder: dict) -> dict:
    cached = _COMPILED.get(id(builder))
    if cached is not None and cached[0] is builder:
        return cached[1]
    compiled = compile_builder(builder)
    if len(_COMPILED) >= _COMPILED_LIMIT:
        _COMPILED.clear()
    _COMPILED[id(builder)] = (builder, compiled)
    return compiled


# --------------------------------------------------------------------------- #
# reading text and codes (contract section 2)
# --------------------------------------------------------------------------- #
def builder_of(rule) -> dict:
    """The builder of a stored rule, or an empty dict for anything else."""
    if isinstance(rule, dict) and isinstance(rule.get("builder"), dict):
        return rule["builder"]
    return {}


def _number(raw: str):
    value = float(raw)
    return int(value) if value.is_integer() else value


def _texts_to_read(look_in: str, texts: dict[str, str]) -> list[str]:
    if look_in == "name":
        return ["class_tail"]
    if look_in in {"description", "flyer"}:
        return [look_in]
    return ["description", "flyer"]


def _skipped(skip: str | None, haystack: str, start: int) -> bool:
    return bool(skip) and _regex(skip).search(haystack[:start]) is not None


def _size_read(compiled: dict, haystack: str):
    """(number, evidence) for a size pick, or None.

    A numbered pick reads the nth number of the FIRST size in the text, and nothing when
    that size has no nth number. A labelled pick reads the number labelled L, W or H in
    the first size that labels one.
    """
    pick = compiled.get("pick")
    pattern = _regex(compiled["pattern"])
    if isinstance(pick, str):
        wanted = pick.upper()
        for match in pattern.finditer(haystack):
            for label_group in (1, 3, 5, 7):
                if match.group(label_group) == wanted:
                    return _number(match.group(label_group + 1)), match.group(0)
        return None
    match = pattern.search(haystack)
    if not match:
        return None
    try:
        position = int(pick)
    except (TypeError, ValueError):
        return None
    if not 1 <= position <= 4:
        return None
    raw = match.group(position * 2)
    if raw is None:
        return None
    return _number(raw), match.group(0)


def read_text(builder: dict, texts: dict[str, str], code: str, spec_key: str | None = None):
    """(value, evidence, which_text) for a words / number / size / code rule, or None.

    Never raises: a builder that cannot compile reads nothing, and the next rule is
    tried. Product rules read the product record and are answered by the caller.
    """
    kind = builder.get("kind")
    try:
        if kind == "code":
            texts_to_find = [str(t).upper() for t in builder.get("texts") or [] if str(t).strip()]
            code_match = builder.get("code_match")
            for needle in texts_to_find:
                if code_match == "ends_with":
                    hit = code.endswith(needle)
                elif code_match == "starts_with":
                    hit = code.startswith(needle)
                elif code_match == "contains":
                    hit = needle in code
                else:
                    return None
                if hit:
                    return builder.get("value"), needle, "code"
            return None
        if kind not in {"words", "number", "size"}:
            return None
        if kind == "words" and not builder.get("words"):
            return None
        if kind == "number" and not (builder.get("before") or builder.get("after")):
            return None

        compiled = compiled_for(builder)
        look_in = builder.get("look_in") or default_look_in(spec_key)
        for name in _texts_to_read(look_in, texts):
            haystack = texts.get(name, "")
            if not haystack:
                continue
            if kind == "size":
                found = _size_read(compiled, haystack)
                if found is not None:
                    return found[0], found[1], name
                continue
            for match in _regex(compiled["pattern"]).finditer(haystack):
                if _skipped(compiled.get("skip"), haystack, match.start()):
                    continue
                if kind == "words":
                    return builder.get("value"), match.group(0), name
                raw = match.group(1)
                if raw is None:
                    continue
                value = _number(raw)
                floor = compiled.get("min")
                if floor is not None and value < float(floor):
                    continue
                scale = compiled.get("scale")
                if scale:
                    value = value * float(scale)
                    if float(value).is_integer():
                        value = int(value)
                return value, match.group(0), name
    except (re.error, TypeError, ValueError):
        return None
    return None


def gate_passes(builder: dict, held: dict) -> bool:
    """Whether the rule's Only when is met by what this derivation has read so far.

    `is: true` needs the other spec to hold one of the values; `is: false` needs it not
    to. A spec the derivation has not read leaves `is: false` met and `is: true` unmet,
    which is exactly how the old `applies_when` / `unless` gates behaved.
    """
    only_when = builder.get("only_when")
    if not isinstance(only_when, dict) or not only_when.get("spec"):
        return True
    value = held.get(only_when["spec"])
    allowed = {str(v).strip().lower() for v in only_when.get("values") or []}
    hit = value is not None and str(value).strip().lower() in allowed
    return hit is bool(only_when.get("is", True))


def gate_keys(rules_by_key: dict[str, list[dict]]) -> set[str]:
    """Keys some rule's Only when reads, so they are derived before the rules that need them."""
    keys: set[str] = set()
    for rules in (rules_by_key or {}).values():
        for rule in rules or []:
            only_when = builder_of(rule).get("only_when")
            if isinstance(only_when, dict) and only_when.get("spec"):
                keys.add(str(only_when["spec"]))
    return keys


