def _gate_to_only_when(rule: dict) -> dict | None:
    gates = []
    for field, is_ in (("applies_when", True), ("unless", False)):
        for spec, values in (rule.get(field) or {}).items():
            values = [str(v) for v in values or [] if str(v).strip()]
            if values:
                gates.append({"spec": str(spec), "is": is_, "values": values})
    if len(gates) > 1:
        raise UnconvertibleRule("it has more than one condition")
    return gates[0] if gates else None


def legacy_to_builder(rule: dict, spec_key: str | None = None) -> dict:
    """The builder a rule stored before builders existed means. Raises UnconvertibleRule.

    Used by tests and scripts to read the frozen pre-lane rules. The S1 migration
    carries its own frozen copy of this mapping, because a migration must not change
    when this module does.
    """
    if builder_of(rule).get("kind") in KINDS:
        return dict(builder_of(rule))
    match = str(rule.get("match") or "contains").lower()
    pattern = str(rule.get("pattern") or "")
    look_in = _SOURCE_TO_LOOK_IN.get(str(rule.get("source") or "any"), None) or "any"
    if look_in == "any":
        look_in = default_look_in(spec_key)
    only_when = _gate_to_only_when(rule)
    legacy = builder_of(rule)
    legacy_kind = legacy.get("kind")

    builder: dict | None = None
    if match == "contains" and pattern:
        builder = {
            "kind": "words",
            "look_in": look_in,
            "words": [pattern],
            "value": rule.get("value"),
        }
    elif match == "ends_with" and pattern:
        builder = {
            "kind": "words",
            "look_in": look_in,
            "words": [pattern],
            "at_end": True,
            "value": rule.get("value"),
        }
    elif match == "code_suffix" and pattern:
        builder = {
            "kind": "code",
            "code_match": "ends_with",
            "texts": [f"-{pattern.upper()}"],
            "value": rule.get("value"),
        }
    elif match in {"code_contains", "code_starts_with"} and pattern:
        builder = {
            "kind": "code",
            "code_match": "contains" if match == "code_contains" else "starts_with",
            "texts": [pattern],
            "value": rule.get("value"),
        }
    elif match == "from_field" and pattern in _FIELD_TO_FACT:
        builder = {"kind": "product", "fact": _FIELD_TO_FACT[pattern]}
    elif match == "name_head":
        builder = {"kind": "product", "fact": "name"}
    elif match == "regex" and pattern == _SIZE_REGEX_V1 and rule.get("capture"):
        builder = {"kind": "size", "look_in": look_in, "pick": int(rule["capture"])}
    elif legacy_kind in {"number_before", "number_after"} and legacy.get("word"):
        part = "before" if legacy_kind == "number_before" else "after"
        builder = {"kind": "number", "look_in": look_in, part: [legacy["word"]]}
    elif legacy_kind == "number_between" and legacy.get("from") and legacy.get("to"):
        builder = {
            "kind": "number",
            "look_in": look_in,
            "after": [legacy["from"]],
            "before": [legacy["to"]],
        }
    elif legacy_kind == "size_triple":
        builder = {"kind": "size", "look_in": look_in, "pick": int(legacy.get("position") or 1)}
    elif match == "present" and pattern and _SPEAKABLE.fullmatch(pattern):
        builder = {
            "kind": "words",
            "look_in": look_in,
            "words": [pattern],
            "value": rule.get("value", True),
        }
    if builder is None:
        raise UnconvertibleRule(f"{match} {pattern!r} has no kind that can express it")
    if rule.get("scale") and builder["kind"] == "number":
        scale = float(rule["scale"])
        builder["written_in"] = {10.0: "centimetres", 1000.0: "metres"}.get(scale)
        if builder["written_in"] is None:
            raise UnconvertibleRule(f"a scale of {rule['scale']} has no unit")
    if only_when:
        builder["only_when"] = only_when
    return clean_builder(builder)
