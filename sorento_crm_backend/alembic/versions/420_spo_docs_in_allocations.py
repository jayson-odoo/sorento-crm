def on_order_from_spo_documents(bind) -> str:
    """`scm.on_order_v` with SPO documents in it.

    Two changes from migration 337, and one rule each:

      * LEFT JOIN to the shipment - a shipping order with no container booked is still
        stock on its way, and the inner join dropped every one of them.
      * `warehouse_id IS NOT NULL` - 6,520 lines name a location we do not hold, and supply
        that cannot be placed must not be counted at a location. It is counted NOWHERE
        rather than everywhere; `location_code` keeps the evidence for a human to fix.

    `line_status` joins the predicate for the same reason the purchase-order view carried
    it: a closed line has left the book. History is written closed AND fully received, so it
    fails both halves and is excluded by construction rather than by a filter to remember.
    """
    return f"""
CREATE OR REPLACE VIEW "{_schema(bind, 'scm')}".on_order_v AS
SELECT sa.product_id,
       sa.warehouse_id,
       SUM((sa.allocated_quantity - COALESCE(sa.quantity_received, 0))::numeric) AS on_order
FROM spo_allocations sa
LEFT JOIN inbound_shipments s ON s.id = sa.inbound_shipment_id
-- Guard, not decoration: `spo_allocations_product_id_fkey` is NOT VALID, so rows predating
-- it were never checked and an orphan in a read model fails the whole analytics run.
JOIN products pr ON pr.id = sa.product_id
WHERE sa.warehouse_id IS NOT NULL
  AND (s.id IS NULL OR s.shipment_status NOT IN {_RECEIVED_SHIPMENT_STATES})
  AND COALESCE(sa.line_status, 'open') = 'open'
  -- `fully_received` is the value the column's CHECK constraint allows. Migration 337
  -- tested `<> 'received'`, which no row has ever carried, so the test could never be
  -- false: a filter that looks like a guard and is not one. Both spellings are listed so
  -- the honest test survives whichever a future writer picks.
  AND COALESCE(sa.receipt_status, 'pending') NOT IN ('fully_received', 'received')
  AND sa.allocated_quantity > COALESCE(sa.quantity_received, 0)
  -- STALENESS (`app/services/scm/spo_supply.py`, the one copy of this rule in Python).
  -- A shipping order nobody has booked a container for, whose promised date has passed,
  -- is not supply: all 715 open SPO lines on the captain's book are past-dated, the
  -- oldest by two years, and no feed refreshes them. A shipment-backed row is never
  -- stale, because its arrival is tracked; a row with no date at all is not stale
  -- either, because nothing says its date has passed.
  AND (sa.inbound_shipment_id IS NOT NULL
       OR sa.expected_date IS NULL
       OR sa.expected_date >= CURRENT_DATE)
GROUP BY sa.product_id, sa.warehouse_id;
"""


def on_order_from_shipped_allocations(bind) -> str:
    """Migration 337's body, for the downgrade. Kept verbatim apart from the schema name."""
    return f"""
CREATE OR REPLACE VIEW "{_schema(bind, 'scm')}".on_order_v AS
SELECT sa.product_id,
       sa.warehouse_id,
       SUM((sa.allocated_quantity - COALESCE(sa.quantity_received, 0))::numeric) AS on_order
FROM spo_allocations sa
JOIN inbound_shipments s ON s.id = sa.inbound_shipment_id
JOIN products pr ON pr.id = sa.product_id
WHERE s.shipment_status NOT IN {_RECEIVED_SHIPMENT_STATES}
  AND sa.receipt_status <> 'received'
  AND sa.allocated_quantity > COALESCE(sa.quantity_received, 0)
GROUP BY sa.product_id, sa.warehouse_id;
"""


