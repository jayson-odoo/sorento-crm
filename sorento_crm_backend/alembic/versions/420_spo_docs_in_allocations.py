def _schema(bind, module: str) -> str:
    """Where a module's tables live, for RAW SQL, under BOTH substrates.

    `schema_translate_map` rewrites ORM and `Table` constructs only, so a hard-coded
    `scm.order_link_claim` in a `text()` statement would reach the REAL schema from a test
    running on a scratch copy - writing live data while the test believed it was isolated
    (the trap `test_migration_400_oi_place_on_po.py` documents from the other direction).
    The scratch schemas are named `<default>_scm` / `<default>_projects`
    (`tests/_pg_fixture.py`), so the current default schema is enough to tell the two apart.
    """
    current = bind.exec_driver_sql("SELECT current_schema()").scalar()
    return module if current in (None, "public") else f"{current}_{module}"


def _default_schema(bind) -> str:
    """Where the unqualified tables live: `public` normally, the scratch schema in a test."""
    return bind.exec_driver_sql("SELECT current_schema()").scalar()


def _has_column(bind, table: str, column: str, schema: str | None = None) -> bool:
    return bool(
        bind.execute(
            sa.text(
                """
                SELECT 1 FROM information_schema.columns
                WHERE table_schema = :schema
                  AND table_name = :table AND column_name = :column
                """
            ),
            {"schema": schema or _default_schema(bind), "table": table, "column": column},
        ).first()
    )


def _has_constraint(bind, name: str, schema: str | None = None) -> bool:
    return bool(
        bind.execute(
            sa.text(
                """
                SELECT 1 FROM pg_constraint c
                JOIN pg_namespace n ON n.oid = c.connamespace
                WHERE n.nspname = :schema AND c.conname = :name
                """
            ),
            {"schema": schema or _default_schema(bind), "name": name},
        ).first()
    )


def _has_index(bind, name: str, schema: str | None = None) -> bool:
    return bool(
        bind.execute(
            sa.text(
                """
                SELECT 1 FROM pg_indexes
                WHERE schemaname = :schema AND indexname = :name
                """
            ),
            {"schema": schema or _default_schema(bind), "name": name},
        ).first()
    )


def _table_exists(bind, schema: str, table: str) -> bool:
    return bool(
        bind.execute(
            sa.text(
                "SELECT 1 FROM information_schema.tables "
                "WHERE table_schema = :schema AND table_name = :table"
            ),
            {"schema": schema, "table": table},
        ).first()
    )


def _qualified(bind, schema, table: str) -> str:
    return f'"{_schema(bind, schema)}"."{table}"' if schema else f'"{table}"'


