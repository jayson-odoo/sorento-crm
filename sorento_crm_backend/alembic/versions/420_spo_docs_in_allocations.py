def reference_counts(bind) -> dict:
    """How many rows outside `purchase_orders` point at an SPO document, per foreign key."""
    counts: dict = {}
    spo_lines = """
        SELECT pl.id FROM purchase_order_lines pl
        JOIN purchase_orders po ON po.id = pl.purchase_order_id
        WHERE po.po_number LIKE 'SPO-%'
    """
    spo_docs = "SELECT id FROM purchase_orders WHERE po_number LIKE 'SPO-%'"
    default_schema = _default_schema(bind)
    for reference in _LINE_REFERENCES + _DOCUMENT_REFERENCES:
        schema, table, column = reference
        where = _schema(bind, schema) if schema else default_schema
        if not _table_exists(bind, where, table):
            continue
        source = spo_docs if reference in _DOCUMENT_REFERENCES else spo_lines
        name = f"{schema}.{table}.{column}" if schema else f"{table}.{column}"
        counts[name] = bind.execute(
            sa.text(
                f"SELECT count(*) FROM {_qualified(bind, schema, table)} t "
                f"WHERE t.{column} IN ({source})"
            )
        ).scalar() or 0
    return counts


def move_spo_documents(bind) -> dict:
    """Every `SPO-` document in `purchase_orders`, as `spo_allocations` rows. Set-based.

    One allocation per purchase-order LINE, carrying that line's own id: nothing else
    references those ids today, and keeping them is what lets the downgrade put the same
    lines back rather than a copy of them.
    """
    blocking = {name: n for name, n in reference_counts(bind).items() if n}
    if blocking:
        # Loudly, with the numbers. There is no column on any of these tables that could
        # name an allocation, so re-pointing is not available and the alternatives are to
        # orphan the row or to cascade the delete into it. Neither is this migration's
        # decision to make silently.
        raise RuntimeError(
            "SPO documents are referenced by rows that cannot be re-pointed at an "
            f"allocation: {blocking}. Resolve them before running migration 420."
        )

    expected = bind.execute(
        sa.text(
            """
            SELECT count(*) FROM purchase_order_lines pl
            JOIN purchase_orders po ON po.id = pl.purchase_order_id
            WHERE po.po_number LIKE 'SPO-%'
            """
        )
    ).scalar() or 0

    moved = bind.execute(
        sa.text(
            """
            WITH src AS (
                SELECT pl.id, pl.product_id, pl.warehouse_id, pl.qty_ordered, pl.qty_received,
                       pl.unit_cost, pl.expected_date, pl.line_status, pl.created_at,
                       pl.purchase_order_id, pl.company_id,
                       COALESCE(pl.currency, po.currency) AS currency,
                       po.po_number, po.issue_date, po.supplier_id, po.source_system,
                       w.warehouse_code,
                       NULLIF(regexp_replace(COALESCE(pl.source_ref, ''), '[^0-9]', '', 'g'), '')::int AS ref_no
                FROM purchase_order_lines pl
                JOIN purchase_orders po ON po.id = pl.purchase_order_id
                LEFT JOIN warehouses w ON w.id = pl.warehouse_id
                WHERE po.po_number LIKE 'SPO-%'
            ), numbered AS (
                SELECT src.*,
                       COALESCE(
                           src.ref_no,
                           -- The live outstanding extract states no line number at all
                           -- (715 lines). They are numbered after whatever the document
                           -- does state, in creation order, so a re-upload of the same
                           -- document lands on the same numbers.
                           COALESCE(MAX(src.ref_no) OVER (PARTITION BY src.purchase_order_id), 0)
                           + row_number() OVER (
                               PARTITION BY src.purchase_order_id, (src.ref_no IS NULL)
                               ORDER BY src.created_at, src.id
                           )
                       ) AS line_no
                FROM src
            )
            INSERT INTO spo_allocations (
                id, spo_number, spo_line_number, product_id, warehouse_id, location_code,
                allocated_quantity, quantity_received, quantity_rejected, receipt_status,
                line_status, source_system, issue_date, expected_date, supplier_id,
                unit_cost, currency, company_id, created_at, synced_to_excel
            )
            SELECT n.id, n.po_number, n.line_no, n.product_id, n.warehouse_id, n.warehouse_code,
                   ROUND(n.qty_ordered)::int, ROUND(COALESCE(n.qty_received, 0))::int, 0,
                   CASE
                       WHEN COALESCE(n.qty_received, 0) >= n.qty_ordered THEN 'fully_received'
                       WHEN COALESCE(n.qty_received, 0) > 0 THEN 'partial_received'
                       ELSE 'pending'
                   END,
                   n.line_status, n.source_system, n.issue_date, n.expected_date, n.supplier_id,
                   n.unit_cost, n.currency, n.company_id, n.created_at, false
            FROM numbered n
            ON CONFLICT DO NOTHING
            """
        )
    ).rowcount or 0

    if moved != expected:
        # `ON CONFLICT DO NOTHING` is what makes a re-run safe, and it is also the one way
        # this move could lose a line without saying so: a line whose
        # (company, document, line number) an existing allocation already holds would
        # simply not arrive. The delete below is about to remove the source, so the
        # discrepancy is checked while both sides still exist.
        raise RuntimeError(
            f"migration 420: {expected} SPO lines to move but {moved} allocations were "
            f"written; {expected - moved} collided with rows already in spo_allocations. "
            "Nothing has been deleted."
        )

    scm = _schema(bind, "scm")
    cleared = 0
    if _table_exists(bind, scm, "order_link_claim"):
        # The claim keeps both document numbers, which is its stated identity; only the
        # resolver's cache of where the PO number landed is cleared, and `resolved_at` with
        # it so "resolved" still means "both halves found".
        cleared = bind.execute(
            sa.text(
                f"""
                UPDATE "{scm}"."order_link_claim" c
                SET po_line_id = NULL, resolved_at = NULL
                FROM purchase_order_lines pl
                JOIN purchase_orders po ON po.id = pl.purchase_order_id
                WHERE pl.id = c.po_line_id AND po.po_number LIKE 'SPO-%'
                """
            )
        ).rowcount or 0

    lines = bind.execute(
        sa.text(
            """
            DELETE FROM purchase_order_lines pl
            USING purchase_orders po
            WHERE po.id = pl.purchase_order_id AND po.po_number LIKE 'SPO-%'
            """
        )
    ).rowcount or 0
    docs = bind.execute(
        sa.text("DELETE FROM purchase_orders WHERE po_number LIKE 'SPO-%'")
    ).rowcount or 0

    logger.info(
        "migration 420: moved %s SPO lines into spo_allocations, deleted %s lines and "
        "%s documents, cleared %s order-link claims",
        moved, lines, docs, cleared,
    )
    return {"allocations": moved, "lines_deleted": lines, "documents_deleted": docs,
            "claims_cleared": cleared}


def restore_spo_documents(bind) -> dict:
    """Put the stamped allocations back as `purchase_orders` / `purchase_order_lines`.

    A document is born `active` when any of its lines is still open and `closed` otherwise -
    which is what it was, because history is written closed and the outstanding extract's
    lines are the only open ones in the set.
    """
    docs = bind.execute(
        sa.text(
            f"""
            INSERT INTO purchase_orders (
                id, po_number, supplier_id, issue_date, status, currency,
                source_system, company_id
            )
            SELECT gen_random_uuid(), sa.spo_number, MIN(sa.supplier_id::text)::uuid,
                   MIN(sa.issue_date),
                   CASE WHEN bool_or(COALESCE(sa.line_status, 'open') = 'open')
                        THEN 'active' ELSE 'closed' END,
                   MIN(sa.currency), MIN(sa.source_system), sa.company_id
            FROM spo_allocations sa
            WHERE sa.spo_number IS NOT NULL
              AND sa.source_system IS NOT NULL
            GROUP BY sa.company_id, sa.spo_number
            """
        )
    ).rowcount or 0

    lines = bind.execute(
        sa.text(
            """
            INSERT INTO purchase_order_lines (
                id, purchase_order_id, product_id, warehouse_id, qty_ordered, qty_received,
                unit_cost, currency, expected_date, line_status, source_system, source_ref,
                created_at, company_id
            )
            SELECT sa.id, po.id, sa.product_id, sa.warehouse_id, sa.allocated_quantity,
                   COALESCE(sa.quantity_received, 0), sa.unit_cost, sa.currency,
                   sa.expected_date, COALESCE(sa.line_status, 'open'), sa.source_system,
                   sa.spo_line_number::text, sa.created_at, sa.company_id
            FROM spo_allocations sa
            JOIN purchase_orders po
              ON po.po_number = sa.spo_number AND po.company_id = sa.company_id
            WHERE sa.spo_number IS NOT NULL
              AND sa.source_system IS NOT NULL
            """
        )
    ).rowcount or 0

    scm = _schema(bind, "scm")
    claims = 0
    if _table_exists(bind, scm, "order_link_claim"):
        # The resolver's own rule (`order_link_service._resolve`): a claim naming an item
        # takes that item's line on the document, one naming none takes the document's
        # first line. Deterministic by line number, where the resolver takes whichever the
        # query returned first.
        claims = bind.execute(
            sa.text(
                f"""
                UPDATE "{scm}"."order_link_claim" c
                SET po_line_id = pick.line_id,
                    spo_allocation_id = NULL,
                    resolved_at = CASE WHEN c.so_line_id IS NOT NULL THEN now() ELSE NULL END
                FROM (
                    SELECT DISTINCT ON (po.po_number, p.product_code)
                           po.po_number, p.product_code, pl.id AS line_id
                    FROM purchase_order_lines pl
                    JOIN purchase_orders po ON po.id = pl.purchase_order_id
                    JOIN products p ON p.id = pl.product_id
                    WHERE po.po_number LIKE 'SPO-%'
                    ORDER BY po.po_number, p.product_code, pl.source_ref, pl.id
                ) pick
                WHERE c.po_line_id IS NULL
                  AND c.item_code IS NOT NULL
                  AND c.po_number = pick.po_number
                  AND c.item_code = pick.product_code
                """
            )
        ).rowcount or 0
        # The item-less half, which the upgrade also re-points: a `**SO:174830**` note in a
        # PO export names no item, so it anchors on the document's first line. Nought of
        # them name an SPO on the captain's book today, which is exactly why it has to be
        # written rather than left for the day one does.
        claims += bind.execute(
            sa.text(
                f"""
                UPDATE "{scm}"."order_link_claim" c
                SET po_line_id = pick.line_id,
                    spo_allocation_id = NULL,
                    resolved_at = CASE WHEN c.so_line_id IS NOT NULL THEN now() ELSE NULL END
                FROM (
                    SELECT DISTINCT ON (po.po_number)
                           po.po_number, pl.id AS line_id
                    FROM purchase_order_lines pl
                    JOIN purchase_orders po ON po.id = pl.purchase_order_id
                    WHERE po.po_number LIKE 'SPO-%'
                    ORDER BY po.po_number, pl.source_ref, pl.id
                ) pick
                WHERE c.po_line_id IS NULL
                  AND c.item_code IS NULL
                  AND c.po_number = pick.po_number
                """
            )
        ).rowcount or 0

    removed = bind.execute(
        sa.text(
            "DELETE FROM spo_allocations WHERE spo_number IS NOT NULL "
            "AND source_system IS NOT NULL"
        )
    ).rowcount or 0

    logger.info(
        "migration 420 downgrade: restored %s documents and %s lines, re-resolved %s claims, "
        "removed %s allocations", docs, lines, claims, removed,
    )
    return {"documents": docs, "lines": lines, "claims": claims, "allocations_removed": removed}


