"""SPO documents live in `spo_allocations`, not in `purchase_orders`

Revision ID: 420_spo_docs_in_allocations
Revises: 419_stock_transfers
Create Date: 2026-08-26 12:00:00.000000

`PLAN-scm-cs-planning-uat.md` section K, captain's Q6 ruling of 25 Aug 2026 (option 1, 26
Aug): a shipping order is not a purchase order, and it moves PHYSICALLY.

Why it matters, measured on the captain's own database: `scm.on_order_v` reads
`spo_allocations` and nothing else, and that table held ONE row, while 3,983 `SPO-`
documents (79,968 lines) sat in `purchase_orders`. Every shipping order was therefore
invisible as incoming supply, and rung 1 of the fulfilment ladder - "an SPO already on its
way" - could never fire for anything. Netting a document family out of the supply read model
by filing it in the wrong table is not a filter somebody forgot; it is the table being wrong.

What moves, and what each family costs:

| `source_system` | documents | lines | lines with no warehouse |
| --- | --- | --- | --- |
| `scm_spo_history` | 3,517 | 74,016 | 1,283 |
| `scm_po_history`  |   414 |  5,237 | 5,237 (the banded report names no location) |
| `scm_upload`      |    52 |    715 | 0 (the only OPEN lines in the set) |

Routing is by the `SPO-` NUMBER, never by the stamp: the number is what the business quotes
and what cannot be typed wrong without being visibly wrong (the same authority
`po_listing_reader.doc_family` uses, and the reason nine rows of the 2023 book disagree with
AutoCount's own `Shipping Order` flag).

Three shape changes make the move possible, and each is a fact about the data:

  * `inbound_shipment_id` becomes nullable - a shipping order exists before anybody books a
    container for it.
  * `warehouse_id` becomes nullable and `location_code` arrives - 6,520 lines name a stock
    location we do not hold. The raw code is kept so nothing is lost, and `on_order_v`
    requires a warehouse, so such a row is incoming supply NOWHERE rather than everywhere.
  * the unique key moves from `(spo_number, product_id, warehouse_id)` to
    `(company_id, spo_number, spo_line_number)` - the old triple forbade the 13,305 repeated
    (document, product, location) groups the book actually contains, which are two containers
    of one item on one shipping order.

Hand-written rather than autogenerated, and guarded throughout: the shared dev database is a
prod copy that converges through `create_all` rather than `alembic upgrade` (see
`sorento_crm_backend/CLAUDE.md`), so every step must be a no-op when it has already happened.

The data half is exposed as functions so the test suite can drive it on a scratch schema
without running the whole chain. It refuses loudly rather than orphaning: every foreign key
that points INTO an SPO document is counted first, and anything with nowhere to go raises
with its counts instead of being silently NULLed by `ON DELETE SET NULL`.

`scm.order_link_claim` is the one exception, and it is not an orphan: the claim holds both
document numbers as TEXT and `po_line_id` is only the resolver's cache of where that number
landed (see the model docstring). 12,393 claims name an SPO, so that cache is cleared and
their `resolved_at` with it, and the claim is then re-pointed at the ALLOCATION through a
new column, `spo_allocation_id`. Without that column the claim could never resolve again -
`sales_order_service.with_links` reads `resolved_at`, so 2,989 sales orders would have read
"awaiting purchase order" for ever - and `po_history_service` would have gone on writing
more claims that could not. The downgrade drops the column and re-resolves `po_line_id` by
the resolver's own rule.

**If the migration refuses**, the counts name the table and the column. There is no column
on any of those tables that could point at an allocation, so the remediation is to deal with
the rows before re-running, not to widen the migration:

  * `scm.shipment_line_spo_link.purchase_order_id` / `.purchase_order_line_id` - a packing
    list that was matched to an SPO filed as a purchase order. Delete the link rows for
    those SPO documents (`consolidated_packing_list` rebuilds them from the shipment lines
    on the next match run) and re-run.
  * `picking_lines.po_line_id` - a GRN drawn against an SPO line. NULL the column on those
    rows; the GRN keeps its `spo_number_raw` and `grn_spo_matching` re-places it against the
    allocation, which is the link it should have had.
  * `projects.order_inquiry_rows.po_line_id` / `scm.loading_plan_line.po_line_id` /
    `scm.plan_exception.purchase_order_id` - all measured 0. If one is not, the row was
    placed on a document that is not a purchase order and belongs on the SPO through
    section I's Link SPO, so clear the column and re-place it there.

Not restored by the downgrade: each SPO document's own row id (nothing references it -
measured 0 on both `scm.shipment_line_spo_link.purchase_order_id` and
`scm.plan_exception.purchase_order_id`) and its `source_ref`. Every LINE id round-trips,
because an allocation is created carrying the id of the line it replaces.
"""
