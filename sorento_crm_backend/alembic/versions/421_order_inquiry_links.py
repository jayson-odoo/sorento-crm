#: The states a link change may set. `actioned` / `cancelled` are a person's word about the
#: row and are never touched by anything here.
_LINK_STATES = ("raised", "placed")


def _schema(bind, module: str) -> str:
    """Where a module's tables live, for RAW SQL, under BOTH substrates.

    `schema_translate_map` rewrites ORM and `Table` constructs only, so a hard-coded
    `projects.order_inquiry_rows` inside a `text()` statement would reach the REAL schema
    from a test running on a scratch copy - writing live data while the test believed it
    was isolated. The scratch schemas are named `<default>_projects`
    (`tests/_pg_fixture.py`), so the current default schema is enough to tell them apart.
    The same helper migration 420 carries, for the same reason.
    """
    current = bind.exec_driver_sql("SELECT current_schema()").scalar()
    return module if current in (None, "public") else f"{current}_{module}"


def _rows(bind) -> str:
    return f'"{_schema(bind, "projects")}"."order_inquiry_rows"'


def _links(bind) -> str:
    return f'"{_schema(bind, "projects")}"."order_inquiry_links"'


