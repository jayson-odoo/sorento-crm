"""One order inquiry row per sales-order line, and a child table for its placements

Revision ID: 421_order_inquiry_links
Revises: 420_spo_docs_in_allocations
Create Date: 2026-08-26 15:00:00.000000

`PLAN-scm-cs-planning-uat.md` section 3.I, the captain's ruling of 25 August 2026 walking
SO414285: "1 line here should correspond to 1 line in sales order, so 1 line can be placed
by multiple PO and SPO".

Today `order_inquiry_rows` holds exactly ONE `po_line_id`, so a cascade that needs two
purchase-order lines has nowhere to put the second and SPLITS the row instead. Measured on
the captain's own database: M310-CR-PJ's 8 is two rows (5 + 3 on 202607-S0105), MSK11C's 67
is two rows (10 + 57 on 202608-S0002), B2155-NL-BLUE on SO414341 is SIX rows across two
purchase orders, and SO414285's nine sales-order lines read as eleven instructions on a
screen whose whole job is to say what to buy.

Three things change, and the third is the one with data in it.

**A child table, `projects.order_inquiry_links`.** One row per placement: the row it
belongs to, exactly ONE of `po_line_id` / `spo_allocation_id` (a CHECK, not a convention),
the quantity, who linked it and whether the cascade did. `document` is denormalised beside
the ids because both foreign keys are `ON DELETE SET NULL`, and a link that can no longer
say WHICH document it was on is not evidence of anything.

**`cited_document` on the row.** What CS NAMED for an order back - "202604-S0083",
"SPO-2026/08-0061" - as they spelled it. Not a link: a citation is what the auto-link walk
tries FIRST, before any location tier or date, and a document this system does not hold is
recorded rather than refused (AC-J2). Its own column because `po_ref` / `spo_ref` become
the DERIVED display of the first link, and a citation is a different fact from a placement.

**The verb `BORROW_SHORTFALL` becomes `ORDER_BACK`,** in the data and in the code. One verb
for the two things that are the same instruction: the hole a borrow left at the donor's
location, and the quantity CS marks ORDER BACK on the Order Inquiry Form. It is the one
verb whose links may name an `spo_allocations` row. Measured: 0 rows carry the old value on
the dev copy, so the UPDATE is a no-op there and the rename costs nothing; it is written
anyway because another database may hold some.

**The backfill merges the splits** (AC-I8). Per `(so_line_id, supply_decision_id, verb)`,
among rows in `raised` / `placed` only:

  * the OLDEST row survives and takes the SUM of the group's quantities;
  * every `placed` fragment becomes ONE link on the survivor, carrying its own quantity,
    `po_line_id`, `po_ref` as the document, and the person and time that placed it;
  * the other rows are deleted;
  * a `placed` row that was never split becomes one row plus one link, the same shape;
  * `po_ref` / `po_line_id` are cleared on every row that gained links, because from here
    they are derived from the links and a stale scalar beside a list is a second opinion.

`actioned` and `cancelled` rows are left alone: those states are a person's word about a
row, and merging one into a raised sibling would overwrite it. Rows with no `so_line_id`
are their own row by definition - the Order Inquiry Form's ORDER BACK quantities have no
open sales-order line at all (fixture section 5), and there is nothing to group them by.

Measured dry run on the dev copy, 26 August 2026: 34 rows, of which 4 groups of more than
one (12 rows) merge to 4; 19 placed rows become 19 links; 26 rows remain, and every
`(so_line_id, supply_decision_id)` holds exactly one. SO414285 goes from eleven rows to
nine, which is AC-I6.

**The downgrade splits them back.** A merge cannot be undone row-for-row, but the SHAPE the
old code reads can be rebuilt exactly: one `placed` row per link at that link's quantity
and `po_line_id`, the original row left holding the unlinked remainder (or deleted when
there is none). Row ids differ, the same caveat migration 420 accepted for the documents it
moved; every quantity and every placement round-trips.

Hand-written rather than autogenerated, and guarded throughout: the shared dev database is
a prod copy that converges through `create_all` rather than `alembic upgrade` (see
`sorento_crm_backend/CLAUDE.md`), so every step must be a no-op when it has already
happened. The data half is exposed as functions so a test can drive it on a scratch schema
without running the whole chain.
"""
