def rename_order_back_verb(bind) -> int:
    """`BORROW_SHORTFALL` -> `ORDER_BACK`. Returns how many rows moved."""
    result = bind.execute(
        sa.text(
            f"UPDATE {_rows(bind)} SET verb = 'ORDER_BACK' "
            "WHERE verb = 'BORROW_SHORTFALL'"
        )
    )
    return result.rowcount or 0


def merge_split_rows(bind) -> dict:
    """Merge every split group into one row, and write one link per placed fragment.

    Idempotent by construction: a second run finds no group of more than one and no placed
    row still carrying a `po_line_id`, so it writes nothing.
    """
    states = ", ".join(f"'{state}'" for state in _LINK_STATES)

    # 1. The survivor of each group, and everything that folds into it. Grouped on the
    #    verb as well as the line and the decision: an ORDER and an ORDER BACK on one line
    #    are two instructions, and summing them would state a quantity nobody asked for.
    groups = bind.execute(
        sa.text(
            f"""
            SELECT so_line_id, supply_decision_id, verb, count(*) AS n
            FROM {_rows(bind)}
            WHERE so_line_id IS NOT NULL AND state IN ({states})
            GROUP BY so_line_id, supply_decision_id, verb
            HAVING count(*) > 1
            """
        )
    ).fetchall()

    merged_groups = 0
    rows_removed = 0
    for so_line_id, decision_id, verb, _n in groups:
        decision_clause = (
            "supply_decision_id = :decision"
            if decision_id is not None
            else "supply_decision_id IS NULL"
        )
        params = {"line": so_line_id, "verb": verb}
        if decision_id is not None:
            params["decision"] = decision_id
        members = bind.execute(
            sa.text(
                f"""
                SELECT id, qty, state
                FROM {_rows(bind)}
                WHERE so_line_id = :line AND verb = :verb AND {decision_clause}
                  AND state IN ({states})
                ORDER BY created_at ASC, id ASC
                """
            ),
            params,
        ).fetchall()
        if len(members) < 2:
            continue
        survivor_id = members[0][0]
        total = sum((member[1] or 0) for member in members)
        # Every fragment's links move to the survivor FIRST, so nothing is lost when the
        # fragment row is deleted (the FK would cascade its links away with it).
        for member in members[1:]:
            bind.execute(
                sa.text(
                    f"UPDATE {_links(bind)} SET row_id = :survivor "
                    "WHERE row_id = :member"
                ),
                {"survivor": survivor_id, "member": member[0]},
            )
        bind.execute(
            sa.text(
                f"DELETE FROM {_rows(bind)} WHERE id = ANY(:ids)"
            ),
            {"ids": [member[0] for member in members[1:]]},
        )
        bind.execute(
            sa.text(f"UPDATE {_rows(bind)} SET qty = :qty WHERE id = :id"),
            {"qty": total, "id": survivor_id},
        )
        merged_groups += 1
        rows_removed += len(members) - 1

    return {"merged_groups": merged_groups, "rows_removed": rows_removed}


def links_from_placed_rows(bind) -> int:
    """One link per row still carrying a `po_line_id`, then clear the scalar.

    Runs BEFORE the merge in `upgrade`, so a fragment's placement is already a link row by
    the time the merge re-points it at the survivor. `qty` comes from the row itself,
    which is exactly what a split fragment's quantity was: its allocation.
    """
    states = ", ".join(f"'{state}'" for state in _LINK_STATES)
    result = bind.execute(
        sa.text(
            f"""
            INSERT INTO {_links(bind)}
                (id, company_id, row_id, po_line_id, spo_allocation_id, document, qty,
                 linked_by, linked_at, auto, claim_id, created_at)
            SELECT gen_random_uuid(), r.company_id, r.id, r.po_line_id, NULL, r.po_ref,
                   r.qty, r.actioned_by, COALESCE(r.actioned_at, now()), false, NULL, now()
            FROM {_rows(bind)} r
            WHERE r.po_line_id IS NOT NULL
              AND r.state IN ({states})
              AND r.qty > 0
              AND NOT EXISTS (
                  SELECT 1 FROM {_links(bind)} l WHERE l.row_id = r.id
              )
            """
        )
    )
    written = result.rowcount or 0
    bind.execute(
        sa.text(
            f"UPDATE {_rows(bind)} SET po_line_id = NULL "
            f"WHERE po_line_id IS NOT NULL AND EXISTS ("
            f"SELECT 1 FROM {_links(bind)} l WHERE l.row_id = {_rows(bind)}.id)"
        )
    )
    return written


def refresh_link_states(bind) -> int:
    """Set every row's state and derived display from its links.

    `raised` with no links, `partly_linked` while the links cover part of the quantity,
    `placed` once they cover it all - the stored value stays `placed` because renaming it
    would rewrite `scm.committed_v`, the worklist filter and every saved column preference
    to say the same thing in a different word. `po_ref` is the FIRST link's document.
    """
    states = ", ".join(f"'{state}'" for state in _LINK_STATES)
    result = bind.execute(
        sa.text(
            f"""
            WITH totals AS (
                SELECT r.id,
                       r.qty AS need,
                       COALESCE(SUM(l.qty), 0) AS linked,
                       -- The FIRST link's document, by when it was made: "first" is an
                       -- order in time, and MIN() would have answered alphabetically.
                       (SELECT f.document
                          FROM {_links(bind)} f
                         WHERE f.row_id = r.id
                         ORDER BY f.linked_at ASC, f.id ASC
                         LIMIT 1) AS document
                FROM {_rows(bind)} r
                LEFT JOIN {_links(bind)} l ON l.row_id = r.id
                WHERE r.state IN ({states}, 'partly_linked')
                GROUP BY r.id, r.qty
            )
            UPDATE {_rows(bind)} r
            SET state = CASE
                    WHEN t.linked <= 0 THEN 'raised'
                    WHEN t.linked < t.need THEN 'partly_linked'
                    ELSE 'placed'
                END,
                po_ref = t.document
            FROM totals t
            WHERE r.id = t.id
              AND (r.state IS DISTINCT FROM CASE
                    WHEN t.linked <= 0 THEN 'raised'
                    WHEN t.linked < t.need THEN 'partly_linked'
                    ELSE 'placed'
                END
                OR r.po_ref IS DISTINCT FROM t.document)
            """
        )
    )
    return result.rowcount or 0


def split_rows_from_links(bind) -> int:
    """The downgrade's data half: rebuild the shape the pre-421 code reads.

    One `placed` row per link, at that link's quantity and `po_line_id`; the original row
    keeps the unlinked remainder as `raised`, or is deleted when the links covered it
    whole. Row ids differ from the ones the upgrade merged away - nothing else does.
    """
    rows = bind.execute(
        sa.text(
            f"""
            SELECT r.id, r.qty, r.company_id, r.order_inquiry_id, r.so_line_id,
                   r.item_code, r.delivery_date, r.stock_location, r.verb,
                   r.covered_by, r.supply_decision_id, r.note, r.redirected_to_pool,
                   r.created_at
            FROM {_rows(bind)} r
            WHERE EXISTS (SELECT 1 FROM {_links(bind)} l WHERE l.row_id = r.id)
            """
        )
    ).fetchall()

    written = 0
    for row in rows:
        links = bind.execute(
            sa.text(
                f"SELECT id, po_line_id, document, qty, linked_by, linked_at "
                f"FROM {_links(bind)} WHERE row_id = :row "
                "ORDER BY linked_at ASC, id ASC"
            ),
            {"row": row[0]},
        ).fetchall()
        if not links:
            continue
        linked_total = sum((link[3] or 0) for link in links)
        remainder = (row[1] or 0) - linked_total

        for index, link in enumerate(links):
            reuse_original = index == 0 and remainder <= 0
            if reuse_original:
                bind.execute(
                    sa.text(
                        f"UPDATE {_rows(bind)} SET qty = :qty, "
                        "po_line_id = :po_line, po_ref = :document, state = 'placed', "
                        "actioned_by = :by, actioned_at = :at WHERE id = :id"
                    ),
                    {
                        "qty": link[3],
                        "po_line": link[1],
                        "document": link[2],
                        "by": link[4],
                        "at": link[5],
                        "id": row[0],
                    },
                )
            else:
                bind.execute(
                    sa.text(
                        f"""
                        INSERT INTO {_rows(bind)}
                            (id, company_id, order_inquiry_id, so_line_id, item_code, qty,
                             delivery_date, stock_location, verb, covered_by,
                             supply_decision_id, note, po_ref, po_line_id,
                             redirected_to_pool, state, actioned_by, actioned_at,
                             created_at)
                        VALUES
                            (gen_random_uuid(), :company, :inquiry, :line, :item, :qty,
                             :delivery, :location, :verb, :covered, :decision, :note,
                             :document, :po_line, :redirected, 'placed', :by, :at,
                             :created)
                        """
                    ),
                    {
                        "company": row[2],
                        "inquiry": row[3],
                        "line": row[4],
                        "item": row[5],
                        "qty": link[3],
                        "delivery": row[6],
                        "location": row[7],
                        "verb": row[8],
                        "covered": row[9],
                        "decision": row[10],
                        "note": row[11],
                        "document": link[2],
                        "po_line": link[1],
                        "redirected": row[12],
                        "by": link[4],
                        "at": link[5],
                        "created": row[13],
                    },
                )
                written += 1

        if remainder > 0:
            bind.execute(
                sa.text(
                    f"UPDATE {_rows(bind)} SET qty = :qty, state = 'raised', "
                    "po_line_id = NULL, po_ref = NULL WHERE id = :id"
                ),
                {"qty": remainder, "id": row[0]},
            )
    return written


